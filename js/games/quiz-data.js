// Räknefrågor skapas på plats, så de tar aldrig slut.
const r = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
export function mathQuestion(t, lang) {
  let a, b, op, ans;
  if (t === 1) { a = r(1, 5); b = r(1, 4); op = '+'; ans = a + b; }
  else if (t === 2) { const k = Math.random(); if (k < 0.4) { a = r(5, 50); b = r(2, 30); op = '+'; ans = a + b; } else if (k < 0.7) { a = r(10, 60); b = r(1, a); op = '-'; ans = a - b; } else { a = r(2, 9); b = r(2, 9); op = '×'; ans = a * b; } }
  else { const k = Math.random(); if (k < 0.35) { a = r(3, 12); b = r(3, 12); op = '×'; ans = a * b; } else if (k < 0.6) { b = r(2, 12); ans = r(2, 12); a = b * ans; op = '÷'; } else if (k < 0.8) { a = r(50, 500); b = r(20, 400); op = '+'; ans = a + b; } else { a = r(100, 999); b = r(10, a); op = '-'; ans = a - b; } }
  const spoken = lang === 'en' ? { '+': 'plus', '-': 'minus', '×': 'times', '÷': 'divided by' }[op] : { '+': 'plus', '-': 'minus', '×': 'gånger', '÷': 'delat med' }[op];
  const q = lang === 'en' ? `What is ${a} ${spoken} ${b}?` : `Hur mycket är ${a} ${spoken} ${b}?`;
  return { t, lang, q, a: [String(ans)], math: true, show: `${a} ${op} ${b} = ?` };
}

